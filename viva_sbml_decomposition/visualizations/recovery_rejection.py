"""NonRecoverabilityEvidence — the covering figure for the adversarial recovery
study ``recover-stochastic-abm`` ("Reject a stochastic system").

The study's claim is a REJECTION: the recovery pipeline must refuse to fit a flat
SBML reaction network to a single low-copy stochastic trajectory. A rejection is
still a result, and it still needs a figure that SHOWS it — otherwise the study
reads "Completed" with an empty Visualizations tab (the gap that motivated this).

This figure makes the rejection legible, from REAL data regenerated by the same
detector the study's run used (``NonRecoverabilityDetector`` / ``_poly_rhs_min_r2``
in ``processes/recovery.py``), not a canned artifact:

  left  — the stochastic (Gillespie) trajectory the detector is handed: noisy,
          low-copy A/B/C in molecules, the kind of signal no smooth RHS can fit.
  right — the per-species R^2 of the best-fit polynomial (mass-action) RHS against
          the data-estimated derivatives, versus the 0.9 recoverability threshold.
          All three species sit far below it (min R^2 = 0.0534), which is exactly
          why the detector returns ``non_recoverable`` — the observable (the
          detector verdict) falls outside the acceptance band. That IS the claim.
"""
from __future__ import annotations

from itertools import combinations_with_replacement

from ._plotly import PlotlyVisualization
from ._common import axis, layout

# The adversarial target + detector settings, matching the study's recorded run
# (NonRecoverabilityDetector defaults: Gillespie, seed 0, 201 points, degree 3).
_TARGET = "recover-stochastic-abm"
_N_POINTS = 201
_MAX_DEGREE = 3
_R2_THRESHOLD = 0.9
_SEED = 0

_SPECIES_COLORS = {"A": "#2563eb", "B": "#d97706", "C": "#7c3aed"}
_BAD = "#dc2626"   # below threshold (non-recoverable)
_BAND = "#059669"  # the recoverability threshold


def _per_species_r2(data, times, degree: int) -> list[float]:
    """R^2 of the best-fit polynomial RHS per species — the per-species form of
    ``processes.recovery._poly_rhs_min_r2`` (which returns only the min)."""
    import numpy as np

    n, nsp = data.shape
    cols = [np.ones(n)]
    for d in range(1, degree + 1):
        for combo in combinations_with_replacement(range(nsp), d):
            col = np.ones(n)
            for j in combo:
                col = col * data[:, j]
            cols.append(col)
    M = np.column_stack(cols)
    dxdt = np.gradient(data, times[1] - times[0], axis=0)
    r2s = []
    for i in range(nsp):
        y = dxdt[:, i]
        coef, *_ = np.linalg.lstsq(M, y, rcond=None)
        ss_tot = float(np.sum((y - y.mean()) ** 2))
        r2s.append(1.0 if ss_tot < 1e-12 else 1.0 - float(np.sum((y - M @ coef) ** 2)) / ss_tot)
    return r2s


class NonRecoverabilityEvidence(PlotlyVisualization):
    def inputs(self):
        return {}

    @staticmethod
    def generate_state(config=None):
        import numpy as np
        import tellurium as te

        from ..models.recovery_targets import RECOVERY_TARGETS

        entry = RECOVERY_TARGETS[_TARGET]
        truth, meta = entry["antimony"], entry["meta"]
        observed = list(meta["species"])

        rr = te.loada(truth)
        rr.reset()
        rr.setIntegrator("gillespie")
        try:
            rr.integrator.seed = _SEED
        except Exception:
            pass
        res = np.asarray(
            rr.simulate(0.0, float(meta["t_end"]), _N_POINTS, selections=["time"] + observed)
        )
        times, data = res[:, 0], res[:, 1:]
        r2s = _per_species_r2(data, times, _MAX_DEGREE)

        return {
            "time": [float(t) for t in times],
            "species": {s: [float(v) for v in data[:, i]] for i, s in enumerate(observed)},
            "r2": {s: float(r2s[i]) for i, s in enumerate(observed)},
            "min_r2": float(min(r2s)),
            "threshold": _R2_THRESHOLD,
            "non_recoverable": bool(min(r2s) < _R2_THRESHOLD),
        }

    def figure(self, s):
        species = s["species"]
        r2 = s["r2"]
        min_r2 = s["min_r2"]
        thr = s["threshold"]

        # Left panel: the stochastic trajectories handed to the detector.
        traj = [
            {"type": "scatter", "mode": "lines", "x": s["time"], "y": y, "name": k,
             "line": {"width": 2, "shape": "hv", "color": _SPECIES_COLORS.get(k, "#64748b")},
             "xaxis": "x", "yaxis": "y",
             "hovertemplate": k + "<br>t=%{x:.2f}<br>%{y:.0f} molecules<extra></extra>"}
            for k, y in species.items()
        ]

        # Right panel: per-species best-fit-RHS R^2 vs the recoverability threshold.
        names = list(r2.keys())
        vals = [r2[k] for k in names]
        bars = [{
            "type": "bar", "x": names, "y": vals, "xaxis": "x2", "yaxis": "y2",
            "marker": {"color": [_BAD if v < thr else _BAND for v in vals]},
            "text": [f"{v:.3f}" for v in vals], "textposition": "outside",
            "showlegend": False,
            "hovertemplate": "species %{x}<br>best-RHS R²=%{y:.3f}<extra></extra>",
        }]

        lay = layout(
            "Correctly rejected: a stochastic system has no faithful flat-SBML form",
            (f"min polynomial-RHS R² = {min_r2:.3f} ≪ {thr} threshold → "
             "non-recoverable (the adversarial study passes by refusing to fit)"),
            height=460,
            showlegend=True,
            legend={"orientation": "h", "x": 0, "y": 1.02, "yanchor": "bottom"},
            xaxis=axis("time", domain=[0.0, 0.54]),
            yaxis=axis("molecules (low copy)"),
            xaxis2=axis("species", domain=[0.66, 1.0], anchor="y2"),
            yaxis2=axis("best-fit-RHS R²", anchor="x2", range=[0, 1.05]),
            annotations=[
                {"text": "stochastic trajectory (Gillespie, low copy)",
                 "xref": "x domain", "yref": "y domain", "x": 0.5, "y": 1.06,
                 "showarrow": False, "font": {"size": 11, "color": "#475569"}},
                {"text": "R² below threshold ⇒ no smooth mass-action RHS fits",
                 "xref": "x2 domain", "yref": "y2 domain", "x": 0.5, "y": 1.06,
                 "showarrow": False, "font": {"size": 11, "color": "#475569"}},
            ],
            shapes=[
                # the 0.9 recoverability threshold on the R^2 panel
                {"type": "line", "xref": "x2 domain", "yref": "y2",
                 "x0": 0, "x1": 1, "y0": thr, "y1": thr,
                 "line": {"color": _BAND, "width": 2, "dash": "dash"}},
            ],
        )
        lay["annotations"].append(
            {"text": f"recoverable ≥ {thr}", "xref": "x2 domain", "yref": "y2",
             "x": 0.98, "y": thr, "xanchor": "right", "yanchor": "bottom",
             "showarrow": False, "font": {"size": 10, "color": _BAND}}
        )
        return {"data": traj + bars, "layout": lay}
